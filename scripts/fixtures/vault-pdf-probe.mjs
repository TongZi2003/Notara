import { chromium } from 'playwright';
const url = process.argv[2];
const browser = await chromium.launch();
const page = await browser.newPage();
const logs = [];
page.on('console', m => { const t = m.text(); if (!/ERR_INSUFFICIENT_RESOURCES/.test(t)) logs.push(`[${m.type()}] ${t.slice(0, 500)}`); });
page.on('pageerror', e => logs.push(`[pageerror] ${e.message.slice(0, 500)}`));
const failures = new Map();
page.on('requestfailed', r => { const key = `${r.failure()?.errorText} ${r.url().slice(0, 160)}`; failures.set(key, (failures.get(key) ?? 0) + 1); });
await page.goto(url, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(2500);
const cl = page.getByRole('button', { name: 'Configure later', exact: true });
if (await cl.isVisible().catch(() => false)) await cl.click();
await page.waitForTimeout(800);
await page.getByText('Notara Vault').first().click();
await page.waitForTimeout(1200);
const composer = page.locator('[data-composer-input], [contenteditable="true"], textarea').last();
await composer.click(); await composer.fill('打开资产页'); await composer.press('Enter');
await page.waitForTimeout(2500);
await page.getByText('资产', { exact: true }).first().click();
await page.getByRole('button', { name: /向量讲义\.pdf/ }).waitFor({ state: 'visible', timeout: 20000 });
console.log('tree loaded; clicking pdf');
const t0 = Date.now();
// dispatch click without waiting for protocol round-trip completion semantics
await page.getByRole('button', { name: /向量讲义\.pdf/ }).dispatchEvent('click');
for (let i = 0; i < 12; i++) {
  await page.waitForTimeout(1000);
  const alive = await page.evaluate(() => 1 + 1).then(() => 'alive').catch(() => 'DEAD');
  const canvas = await page.locator('canvas[aria-label="向量讲义.pdf"]').count();
  const spans = await page.locator('.nv-pdf-text span').count();
  console.log(`t=${((Date.now() - t0) / 1000).toFixed(0)}s alive=${alive} canvas=${canvas} textSpans=${spans}`);
  if (canvas && spans > 2) break;
}
await page.screenshot({ path: '/tmp/v-pdf-open.png' });
const canvas = page.locator('canvas[aria-label="向量讲义.pdf"]');
const stage = await canvas.evaluate(node => node.parentElement.getBoundingClientRect());
await page.mouse.move(stage.x + stage.width * 0.06, stage.y + stage.height * 0.06);
await page.mouse.down();
await page.mouse.move(stage.x + stage.width * 0.9, stage.y + stage.height * 0.2, { steps: 8 });
await page.mouse.up();
await page.waitForTimeout(600);
console.log('SELECTION', await page.locator('text=/已框选/').first().innerText().catch(() => 'none'));
await page.getByRole('button', { name: '提取为 Markdown 卡片' }).click();
await page.waitForTimeout(2000);
const hintText = await page.locator('header span').last().innerText().catch(() => '');
console.log('NOTICE', hintText);
console.log('BODYTAIL', (await page.locator('body').innerText()).slice(-800));
console.log('---LOGS---');
logs.slice(0, 30).forEach(l => console.log(l));
console.log('---FAILED REQUESTS---');
[...failures.entries()].forEach(([k, n]) => console.log(`${n}x ${k}`));
await browser.close();
